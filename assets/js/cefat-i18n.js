let currentLang = 'fr';

function setLanguage(lang) {
  if (!cefatTranslations[lang]) return;
  currentLang = lang;
  try {
    localStorage.setItem('cefat_lang', lang);
  } catch (e) {}

  // 1. Text elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (cefatTranslations[lang] && cefatTranslations[lang][key] !== undefined) {
      el.innerHTML = cefatTranslations[lang][key];
    }
  });

  // 2. Input and Textarea placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (cefatTranslations[lang] && cefatTranslations[lang][key] !== undefined) {
      el.setAttribute('placeholder', cefatTranslations[lang][key]);
    }
  });

  // 3. aria-label (boutons sans texte visible : flèches du carrousel)
  document.querySelectorAll('[data-i18n-label]').forEach(el => {
    const key = el.getAttribute('data-i18n-label');
    if (cefatTranslations[lang] && cefatTranslations[lang][key] !== undefined) {
      el.setAttribute('aria-label', cefatTranslations[lang][key]);
    }
  });

  // 4. Values with data-i18n-value
  document.querySelectorAll('[data-i18n-value]').forEach(el => {
    const key = el.getAttribute('data-i18n-value');
    if (cefatTranslations[lang] && cefatTranslations[lang][key] !== undefined) {
      el.setAttribute('value', cefatTranslations[lang][key]);
    }
  });

  // 4. Update language switch active buttons
  document.querySelectorAll('.lang-switch-btn').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  // 5. Update HTML lang tag
  document.documentElement.setAttribute('lang', lang);
}

document.addEventListener('DOMContentLoaded', () => {
  let savedLang = 'fr';
  try {
    savedLang = localStorage.getItem('cefat_lang') || 'fr';
  } catch (e) {}
  setLanguage(savedLang);
});
